/**
 * Разделы для страницы справки.
 *
 * Отдельно от HELP_SECTIONS, потому что `as const` сужает записи до
 * литералов: у темы без `href` этого поля в типе просто нет, и обращение к
 * нему считается ошибкой. Здесь тот же массив, но описанный общим типом.
 */
export const HELP_PAGE: readonly HelpSection[] = HELP_SECTIONS

/** Все идентификаторы тем — чтобы <HelpTip> не сослался на несуществующую. */
export type HelpTopicId =
  (typeof HELP_SECTIONS)[number]['topics'][number]['id']

const INDEX: Record<string, HelpTopic> = {}
for (const section of HELP_SECTIONS) {
  for (const topic of section.topics) INDEX[topic.id] = topic
}

export function helpTopic(id: HelpTopicId): HelpTopic {
  return INDEX[id]
}

